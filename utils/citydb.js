/** 城市名 -> 6 位行政区划码（用于腾讯天气接口）。查不到时回退到省会。 */
function adcodeOf(city) {
  const name = String(city || '').trim()
  if (!name) return ''
  if (CITY_ADCODE[name]) return CITY_ADCODE[name]
  const province = provinceOf(name)
  return province ? (PROVINCE_ADCODE[province] || '') : ''
}

