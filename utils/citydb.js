/** 城市 -> 省份 反查表 */
const CITY_TO_PROVINCE = {}
PROVINCES.forEach((p) => {
  p.cities.forEach((c) => {
    if (!CITY_TO_PROVINCE[c]) CITY_TO_PROVINCE[c] = p.name
  })
})

/** 全部城市（含省份信息） */
function allCities() {
  const out = []
  PROVINCES.forEach((p) => {
    p.cities.forEach((c) => out.push({ city: c, province: p.name }))
  })
  return out
}

/** 省份名（没有收录时返回空串） */
function provinceOf(city) {
  const name = String(city || '').trim()
  if (!name) return ''
  if (CITY_TO_PROVINCE[name]) return CITY_TO_PROVINCE[name]
  // 容错：去掉「市 / 地区 / 自治州」等后缀再试
  const trimmed = name.replace(/(市|地区|自治州|自治县|县|区)$/, '')
  return CITY_TO_PROVINCE[trimmed] || ''
}

/**
 * 模糊搜索城市：前缀命中优先，其次包含命中，最后匹配省份名。
 * @param {string} keyword
 * @param {number} limit
 * @returns {Array<{city:string, province:string}>}
 */
function searchCities(keyword, limit) {
  const max = limit || 30
  const key = String(keyword || '').trim()
  if (!key) {
    return HOT_CITIES.map((c) => ({ city: c, province: provinceOf(c) }))
  }
  const prefix = []
  const contains = []
  const byProvince = []
  allCities().forEach((item) => {
    if (item.city === key) prefix.unshift(item)
    else if (item.city.indexOf(key) === 0) prefix.push(item)
    else if (item.city.indexOf(key) >= 0) contains.push(item)
    else if (item.province.indexOf(key) >= 0) byProvince.push(item)
  })
  return prefix.concat(contains, byProvince).slice(0, max)
}

/** 关键词是否是一个「精确的城市名」 */
function isExactCity(keyword) {
  return !!CITY_TO_PROVINCE[String(keyword || '').trim()]
}

/** 省份列表（供二级选择用） */
function listProvinces() {
  return PROVINCES.map((p) => p.name)
}

/** 某省份下的城市 */
function citiesOfProvince(name) {
  const found = PROVINCES.find((p) => p.name === name)
  return found ? found.cities.slice() : []
}



